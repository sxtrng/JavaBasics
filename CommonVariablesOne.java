public class CommonVariablesOne {
    public static void main(String[] args) {

        System.out.println("\n");

        char a = 'x';
        System.out.println("\'char\' holds a single character: " + a);

        String b = "This is a string.";
        System.out.println("\'String\' holds a multiple characters: " + b);


        int c = 48;
        System.out.println("\'int\' holds a whole number: " + c);

        double d = 1.23;
        System.out.println("\'double\' holds a number with decimal places: " + d);


        boolean e = true;
        boolean f = false;
        System.out.println("\'bool\' holds a truth-value: " + e + " or " + f);


        System.out.println("\n");

    }
}

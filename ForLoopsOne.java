public class Main {
    public static void main(String[] args) {


        for (int i = 0; i < 10; i++) {
            System.out.printf("%d ", i);
        }

        System.out.println();

        for (int i = 0; i <= 10; i++) {
            System.out.printf("%d ", i);
        }

        System.out.println();

        for (int i = 0; i < 20; i += 2) {
            System.out.printf("%d ", i);
        }
        System.out.println();

        for (int i = 10; i > 0; i -= 1) {
            System.out.printf("%d ", i);
        }
        System.out.println();

    }
}
public class EscapeSequencesOne {
    public static void main(String[] args) {

        System.out.println("\nThe following list is not exhaustive. It includes the more commonly used escape sequences.\n");


        System.out.println("\t'Backslash t' is used to indent your text.");

        System.out.println("\t'\\t' is used to indent your text.");

        System.out.println("To move the cursor to a new line without using a new print statement, use the newline character: '\\n'.");

        System.out.println("To print a Backslash, type two Backslashes: '\\'  The first Backslash allows the second to be printed.");

        System.out.println("To print a single quote, place a backslash before the single quote mark: \\\'");

        System.out.println("To print a double quotes, place a backslash before the double quote marks: \\\"");

        System.out.println("");

    }
}

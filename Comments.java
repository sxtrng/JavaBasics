public class Comments {
    public static void main(String[] args) {

        // This is a single line comment.
        
        System.out.println("Comments are ignored by the compiler, and will not be printed to the screen or evaluated like code is.");
        System.out.println("Their purpose is to clarify complex code.");
        System.out.println("Read by people, not compilers.");

        /*
            This is
            a multi line
            comment.
        */

        System.out.println("\\\\This is a single line comment.");
        System.out.println("/*Multi line comments can be on one line.*/");
        
    }
}
